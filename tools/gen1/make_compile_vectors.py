#!/usr/bin/env python3
"""Generate tests/gen1_compile_vectors.h: random (made-up) part stats run
through a straight transcription of Master of Arena's compile instructions
(menu module 0x800A7BB4). No game data: inputs are random numbers."""
import random

M = 0xFFFFFFFF
def s32(x):
    x &= M
    return x - (1 << 32) if x >> 31 else x
def mult_hi(a, b): return s32((s32(a) * s32(b)) >> 32)          # mult; mfhi
def multu_hi(a, b): return ((a & M) * (b & M)) >> 32             # multu; mfhi
def sra(x, n): return s32(x) >> n

def compile_ref(p, opt):
    # weight: every part but the generator, capped by legs weight + carry limit
    w = sum(p[k]['w'] for k in ('core','booster','head','arms','blade','hand','backl','backr','fcs','legs') if p[k]['on'])
    cap = p['legs']['w'] + p['legs']['carry']
    if cap < w: w = cap
    # +20 rise drain
    src = p['booster']['2e'] if p['booster']['on'] else p['legs']['44']
    x = s32(src << 12)
    v = sra(mult_hi(x, 0x66666667), 2) - (x >> 31)
    v = sra(v, 12)
    rise = v if v > 0 else 1
    # +22 / +26 refill
    frame = p['head']['2a'] + p['arms']['2a'] + p['core']['2a'] + p['fcs']['2a']
    def refill(drain, mx):
        t = ((p['gen']['2a'] - drain) << 18) & M
        v = multu_hi(t, 0x10624DD3) >> 18
        if v <= 0: v = 1
        return min(v, mx)
    still = refill(frame + p['legs']['34'], 384)
    moving = refill(frame + p['legs']['2a'], 192)
    # +36 stability (legs +0x40, Balancer bonus)
    t = p['legs']['40'] + (0x640 if opt & 0x1000 else 0x320 if opt & 0x8 else 0)
    x = s32(t << 12)
    a = sra(s32(mult_hi(x, 0x80C121B3) + x), 9) - (x >> 31)
    b = multu_hi((w << 8) & M, 0x10624DD3) >> 9
    v = sra(s32(a * b), 14)
    if v < 33: v = 32
    if v >= 256: v = 255
    blade = p['blade']['2c'] if p['blade']['on'] else 0
    # movement bytes +6..+14 (0x800A8038..0x800A8238)
    W = w if w else 1
    P = p['booster']['2c'] if p['booster']['on'] else 0x2648
    a = ((P << 12) & M) // W
    t9 = (a * 9) & M; t73 = (t9 * 8 + a) & M; t = (t73 + ((t73 << 9) & M)) & M; t = (t << 1) & M
    raw = t >> 24
    thrust = min(max(raw, 1), 64) if raw > 0 else 1
    x = s32(raw << 3)
    c = sra(mult_hi(x, 0x66666667), 2) - (x >> 31)
    c = 1 if c <= 0 else c
    c = min(c, 50)
    x = s32(((raw * 3) << 2) & M)
    d = ((mult_hi(x, 0x66666667) & M) >> 2)
    d = 1 if (d & 0xff) == 0 else d
    d = 64 if (d & 0xff) >= 0x41 else d & 0xff
    if p['legs'].get('fb'): d = p['legs']['fb']
    e = p['legs']['38']
    x = s32(((e * 3) << 16) & M)
    f = sra(mult_hi(x, 0x66666667), 6) - (x >> 31)
    g = (((f * 3573) & M) // W) >> 12
    g = 1 if s32(g) <= 0 else g
    g = 64 if s32(g) >= 0x41 else g
    h = (((p['legs']['3a'] & 0xff) * 14635008) & M) // W >> 12
    h = 64 if h >= 0x41 else h
    fr = multu_hi((w << 18) & M, 0x10624DD3) >> 21
    fr = 32 if fr < 32 else fr
    fr = 96 if fr >= 0x61 else fr
    # +18 energy capacity: SP-CND-K (option bit 5) adds 12,000 (u16 store)
    cap18 = (p['gen']['2c'] + (12000 if opt & 0x20 else 0)) & 0xFFFF
    return [cap18, rise, still, p['gen']['2e'], moving, blade, v, w, thrust, c, d, g, h, fr]

random.seed(1)
KEYS = ('core','booster','head','arms','blade','hand','backl','backr','gen','fcs','legs')
rows = []
for n in range(600):
    p = {}
    for k in KEYS:
        big = n % 10 == 0          # some extreme cases
        r = lambda hi: random.randint(0, 65535 if big else hi)
        p[k] = dict(on=1 if k in ('core','head','arms','gen','fcs','legs') else random.randint(0, 1),
                    w=r(3000), **{'2a': r(3000), '2c': r(30000), '2e': r(9000),
                                  'carry': r(6000), '34': r(1500), '40': r(3000), '44': r(9000),
                                  '38': r(400), '3a': random.randint(0, 255), 'fb': random.choice([0, 0, 0, random.randint(1, 30)])})
    if k == 'gen': pass
    p['gen']['2a'] = random.randint(0, 65535 if n % 10 == 0 else 12000)
    opt = random.choice([0, 0, 0x8, 0x1000, 0x1008, random.randint(0, 0xFFFF)])
    rows.append((p, opt, compile_ref(p, opt)))

with open('tests/gen1_compile_vectors.h', 'w') as f:
    f.write('/* Generated by tools/gen1/make_compile_vectors.py: random inputs, not game data. */\n')
    f.write('typedef struct { uint16_t in[11][12]; uint16_t opt; uint32_t out[14]; } gen1_vector;\n')
    f.write('static const gen1_vector k_gen1_vectors[] = {\n')
    for p, opt, out in rows:
        parts = ','.join('{%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d}' % (p[k]['on'], p[k]['w'], p[k]['2a'], p[k]['2c'], p[k]['2e'],
                                                        p[k]['carry'], p[k]['34'], p[k]['40'], p[k]['44'], p[k]['38'], p[k]['3a'],
                                                        p[k]['fb']) for k in KEYS)
        f.write('  {{%s},%d,{%s}},\n' % (parts, opt, ','.join(str(o) for o in out)))
    f.write('};\n')
print('wrote', len(rows), 'vectors')
